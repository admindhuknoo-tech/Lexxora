import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
let pass=0, fail=0;
function check(name, ok){ console.log(`${ok?'PASS':'FAIL'} | ${name}`); ok?pass++:fail++; }
const exp=read('server/exporters.ts');
const ca=read('server/caseAnalysis.ts');
const di=read('server/documentIngestion.ts');
const ev=read('server/evidenceModel.ts');
const fw=read('server/forensicReasoner.ts');
const lw=read('server/lawyerWorkflow.ts');
const legacy=read('scripts/audit-source-quality-guard-v692.ts');
const srv=read('server.ts');
check('A evidence model present', ev.includes('buildEvidenceModel'));
check('A forensic reasoner present', fw.includes('reason'));
check('B canonical analysis readiness helper in exporter', exp.includes('function analysisReadinessScore'));
check('B header/export status uses canonical analysis readiness', exp.includes('STATUS ANALISIS') && exp.includes('analysisReadinessScore(analysis)'));
check('B pipeline gate remains a separate metric', exp.includes('pipelineGateLabel(analysis)'));
check('B analysis readiness is min(pipeline, working paper)', ca.includes('Math.min(pipelineGateReadinessScore, workingPaperReadinessScore)'));
check('B workflow posture implementation present', lw.includes('procedural'));
check('C canonical text resolver exported', ca.includes('export function resolveCanonicalAnalysisText'));
check('C source quality guard exported', di.includes('export function applyOcrSourceQualityGuard'));
check('C span quality guard exported', di.includes('export function applyOcrSpanQualityGuard'));
check('C logical-block sanitation present', /logical.{0,30}block/i.test(di) || /block.{0,30}logical/i.test(di));
check('legacy source-quality audit uses canonical guard', legacy.includes('applyOcrSourceQualityGuard'));
check('legacy source-quality audit uses structured page metrics', legacy.includes("page: 1") && legacy.includes("status: 'OK'"));
check('D liveness endpoint present', srv.includes('/api/live'));
check('D readiness endpoint present', srv.includes('/api/ready'));
check('D health endpoint present', srv.includes('/api/health'));
console.log(`\n${pass}/${pass+fail} canonical-consolidation checks PASS`);
if(fail) process.exit(1);
